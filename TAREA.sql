SELECT SYSDATE AS "Fecha Actual",
       LAST_DAY(ADD_MONTHS(SYSDATE, 12 - TO_NUMBER(TO_CHAR(SYSDATE, 'MM')))) AS "Fin de Anio",
       TRUNC(LAST_DAY(ADD_MONTHS(SYSDATE, 12 - TO_NUMBER(TO_CHAR(SYSDATE, 'MM'))))) - TRUNC(SYSDATE) AS "Dias Restantes"
FROM DUAL;




SELECT FIRST_NAME, LAST_NAME, HIRE_DATE
FROM EMPLOYEES
WHERE TO_CHAR(HIRE_DATE, 'MM') = TO_CHAR(SYSDATE, 'MM');





SELECT LAST_NAME,
       SYSDATE - HIRE_DATE AS "DIAS TRABAJANDO"
FROM EMPLOYEES
WHERE DEPARTMENT_ID = 20
AND SALARY > 6000;




SELECT EMPLOYEE_ID, JOB_ID,
       MONTHS_BETWEEN(END_DATE, START_DATE) AS "NUMERO DE MESES"
FROM JOB_HISTORY
WHERE EMPLOYEE_ID = 101
OR EMPLOYEE_ID = 200
OR EMPLOYEE_ID = 176;




SELECT LAST_NAME, HIRE_DATE
FROM EMPLOYEES
WHERE EXTRACT(YEAR FROM HIRE_DATE) > 2007;






















SELECT FIRST_NAME, LAST_NAME
FROM EMPLOYEES
WHERE EXTRACT(MONTH FROM HIRE_DATE) = EXTRACT(MONTH FROM SYSDATE);




