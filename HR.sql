SELECT * FROM EMPLOYEES;

SELECT DEPARTMENT_ID, MEDIAN(SALARY)
FROM EMPLOYEES
GROUP BY DEPARTMENT_ID;

SELECT STDDEV(SALARY) AS DESVIACION_ESTANDAR FROM EMPLOYEES;

SELECT SESSIONTIMEZONE, CURRENT_DATE FROM DUAL;

SELECT SYSDATE FROM DUAL;

SELECT HIRE_DATE, TO_CHAR(ADD_MONTHS(HIRE_DATE, 10),
'DD-MON-YYYY') AS "MES CALCULADO"
FROM EMPLOYEES
WHERE LAST_NAME = 'Baer';

SELECT SYSDATE AS "Fecha Actual",
       LAST_DAY(ADD_MONTHS(SYSDATE, 12 - TO_NUMBER(TO_CHAR(SYSDATE, 'MM')))) AS "Fin de Año",
       TRUNC(LAST_DAY(ADD_MONTHS(SYSDATE, 12 - TO_NUMBER(TO_CHAR(SYSDATE, 'MM'))))) - TRUNC(SYSDATE) AS "Dias Restantes"
FROM DUAL;

SELECT MONTHS_BETWEEN(TO_DATE('31/12/2025','DD/MM/YYYY'),
TO_DATE(SYSDATE,'DD/MM/YYYY'))
FROM DUAL;

SELECT MONTHS_BETWEEN(TO_DATE(SYSDATE,'DD/MM/YYYY'),
TO_DATE('31/12/2025','DD/MM/YYYY'))
FROM DUAL;

SELECT NEXT_DAY(SYSDATE,'JUEVES')
FROM DUAL;

